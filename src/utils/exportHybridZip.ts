import JSZip from "jszip";
import { slugify, triggerDownload } from "@/export/downloadZip";
import { buildHybridGuideAssets } from "@/export/hybridGuideTemplate";
import type { HybridGuideData, HybridImage } from "@/types/hybridGuide";

const NETLIFY_TOML = "[build]\n  publish = \".\"\n\n[[redirects]]\n  from = \"/*\"\n  to = \"/index.html\"\n  status = 200\n";

function dataUrlToParts(dataUrl: string): { ext: string; base64: string } | null {
  const match = dataUrl.match(/^data:image\/(\w+);base64,(.+)$/);
  if (!match) return null;
  return { ext: match[1] === "jpeg" ? "jpg" : match[1], base64: match[2] };
}

function collectImages(guide: HybridGuideData): HybridImage[] {
  return [
    guide.cover.mainImage,
    ...guide.educationalCards.map((c) => c.image),
    ...guide.preOffer.map((c) => c.image),
    guide.finalCta.productImage,
  ];
}

export async function downloadHybridGuideZip(guide: HybridGuideData): Promise<void> {
  const assetMap = new Map<string, string>();
  const zip = new JSZip();
  const assetsFolder = zip.folder("assets");

  let imageIndex = 0;
  for (const image of collectImages(guide)) {
    if (!image.url) continue;
    if (image.url.startsWith("data:image/")) {
      const parts = dataUrlToParts(image.url);
      if (parts) {
        const fileName = `image-${++imageIndex}.${parts.ext}`;
        assetMap.set(image.url, `assets/${fileName}`);
        if (assetsFolder) assetsFolder.file(fileName, parts.base64, { base64: true });
      }
    }
  }

  const { indexHtml, css, js } = buildHybridGuideAssets(guide, assetMap);

  zip.file("index.html", indexHtml);
  zip.folder("css")?.file("style.css", css);
  zip.folder("js")?.file("app.js", js);
  zip.file("netlify.toml", NETLIFY_TOML);
  zip.file("_redirects", "/*    /index.html   200\n");
  zip.file("README.md", `# ${guide.cover.headline || "Guia Híbrido"}\n\nGenerated by PageClone AI - Hybrid Discovery Guide.\n\n## Deploy\n1. Extract this ZIP\n2. Upload to Netlify Drop, Vercel, or any static host\n`);

  const blob = await zip.generateAsync({ type: "blob", compression: "DEFLATE" });
  triggerDownload(blob, `${slugify(guide.cover.headline) || "guia-hibrido"}.zip`);
}
